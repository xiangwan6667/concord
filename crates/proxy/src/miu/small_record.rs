use std::sync::LazyLock;

use rand::Rng;

static LENGTHS: LazyLock<Vec<(usize, u32)>> = LazyLock::new(|| {
    let mut total = 0;
    UPLINK
        .iter()
        .map(|&(length, count)| {
            total += count;
            (length, total)
        })
        .collect()
});

fn pick(minimum: usize, rng: &mut impl Rng) -> Option<usize> {
    let start = LENGTHS.partition_point(|&(length, _)| length < minimum);
    let base = start
        .checked_sub(1)
        .and_then(|previous| LENGTHS.get(previous))
        .map_or(0, |&(_, cumulative)| cumulative);
    let &(_, total) = LENGTHS.last()?;
    if base == total {
        return None;
    }
    let draw = rng.random_range(base..total);
    LENGTHS
        .get(LENGTHS.partition_point(|&(_, cumulative)| cumulative <= draw))
        .map(|&(length, _)| length)
}

pub(super) fn padding_len(plaintext: usize) -> Option<usize> {
    let wire = plaintext + 17;
    if wire >= 300 {
        return None;
    }
    let mut rng = rand::rng();
    for _ in 0..4 {
        match pick(wire, &mut rng)? {
            target if target == wire => return None,
            target if target >= wire + 3 => return Some(target - wire - 3),
            _ => {}
        }
    }
    pick(wire + 3, &mut rng).map(|target| target - wire - 3)
}

