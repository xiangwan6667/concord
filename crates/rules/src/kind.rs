use concord_config::rule::Cond;

/// The rule type as a connection record shows it (`RuleType.String()` in mihomo).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(u8)]
pub enum RuleKind {
    Domain,
    DomainSuffix,
    DomainKeyword,
    DomainRegex,
    DomainWildcard,
    GeoSite,
    GeoIp,
    SrcGeoIp,
    IpAsn,
    SrcIpAsn,
    IpCidr,
    SrcIpCidr,
    IpSuffix,
    SrcIpSuffix,
    SrcPort,
    DstPort,
    InPort,
    Dscp,
    InUser,
    InName,
    RematchName,
    InType,
    ProcessName,
    ProcessPath,
    ProcessNameRegex,
    ProcessPathRegex,
    ProcessNameWildcard,
    ProcessPathWildcard,
    RuleSet,
    Network,
    Uid,
    SubRules,
    Match,
    And,
    Or,
    Not,
}

impl RuleKind {
    pub fn name(self) -> &'static str {
        match self {
            RuleKind::Domain => "Domain",
            RuleKind::DomainSuffix => "DomainSuffix",
            RuleKind::DomainKeyword => "DomainKeyword",
            RuleKind::DomainRegex => "DomainRegex",
            RuleKind::DomainWildcard => "DomainWildcard",
            RuleKind::GeoSite => "GeoSite",
            RuleKind::GeoIp => "GeoIP",
            RuleKind::SrcGeoIp => "SrcGeoIP",
            RuleKind::IpAsn => "IPASN",
            RuleKind::SrcIpAsn => "SrcIPASN",
            RuleKind::IpCidr => "IPCIDR",
            RuleKind::SrcIpCidr => "SrcIPCIDR",
            RuleKind::IpSuffix => "IPSuffix",
            RuleKind::SrcIpSuffix => "SrcIPSuffix",
            RuleKind::SrcPort => "SrcPort",
            RuleKind::DstPort => "DstPort",
            RuleKind::InPort => "InPort",
            RuleKind::Dscp => "DSCP",
            RuleKind::InUser => "InUser",
            RuleKind::InName => "InName",
            RuleKind::RematchName => "RematchName",
            RuleKind::InType => "InType",
            RuleKind::ProcessName => "ProcessName",
            RuleKind::ProcessPath => "ProcessPath",
            RuleKind::ProcessNameRegex => "ProcessNameRegex",
            RuleKind::ProcessPathRegex => "ProcessPathRegex",
            RuleKind::ProcessNameWildcard => "ProcessNameWildcard",
            RuleKind::ProcessPathWildcard => "ProcessPathWildcard",
            RuleKind::RuleSet => "RuleSet",
            RuleKind::Network => "Network",
            RuleKind::Uid => "Uid",
            RuleKind::SubRules => "SubRules",
            RuleKind::Match => "Match",
            RuleKind::And => "AND",
            RuleKind::Or => "OR",
            RuleKind::Not => "NOT",
        }
    }

    /// `src` is the rule's `src` parameter, which turns `GEOIP`, `IP-CIDR` and
    /// the like into their source variants.
    pub(crate) fn of(cond: &Cond, src: bool) -> RuleKind {
        match cond {
            Cond::Domain(_) => RuleKind::Domain,
            Cond::DomainSuffix(_) => RuleKind::DomainSuffix,
            Cond::DomainKeyword(_) => RuleKind::DomainKeyword,
            Cond::DomainRegex(_) => RuleKind::DomainRegex,
            Cond::DomainWildcard(_) => RuleKind::DomainWildcard,
            Cond::GeoSite(_) => RuleKind::GeoSite,
            Cond::GeoIp(_) if src => RuleKind::SrcGeoIp,
            Cond::GeoIp(_) => RuleKind::GeoIp,
            Cond::SrcGeoIp(_) => RuleKind::SrcGeoIp,
            Cond::IpAsn(_) if src => RuleKind::SrcIpAsn,
            Cond::IpAsn(_) => RuleKind::IpAsn,
            Cond::SrcIpAsn(_) => RuleKind::SrcIpAsn,
            Cond::IpCidr(_) | Cond::IpCidr6(_) if src => RuleKind::SrcIpCidr,
            Cond::IpCidr(_) | Cond::IpCidr6(_) => RuleKind::IpCidr,
            Cond::SrcIpCidr(_) => RuleKind::SrcIpCidr,
            Cond::IpSuffix(_) if src => RuleKind::SrcIpSuffix,
            Cond::IpSuffix(_) => RuleKind::IpSuffix,
            Cond::SrcIpSuffix(_) => RuleKind::SrcIpSuffix,
            Cond::SrcPort(_) => RuleKind::SrcPort,
            Cond::DstPort(_) => RuleKind::DstPort,
            Cond::InPort(_) => RuleKind::InPort,
            Cond::Dscp(_) => RuleKind::Dscp,
            Cond::ProcessName(_) => RuleKind::ProcessName,
            Cond::ProcessPath(_) => RuleKind::ProcessPath,
            Cond::ProcessNameRegex(_) => RuleKind::ProcessNameRegex,
            Cond::ProcessPathRegex(_) => RuleKind::ProcessPathRegex,
            Cond::ProcessNameWildcard(_) => RuleKind::ProcessNameWildcard,
            Cond::ProcessPathWildcard(_) => RuleKind::ProcessPathWildcard,
            Cond::Network(_) => RuleKind::Network,
            Cond::Uid(_) => RuleKind::Uid,
            Cond::InType(_) => RuleKind::InType,
            Cond::InUser(_) => RuleKind::InUser,
            Cond::InName(_) => RuleKind::InName,
            Cond::RematchName(_) => RuleKind::RematchName,
            Cond::And(_) => RuleKind::And,
            Cond::Or(_) => RuleKind::Or,
            Cond::Not(_) => RuleKind::Not,
            Cond::RuleSet(_) => RuleKind::RuleSet,
            Cond::SubRule(_) => RuleKind::SubRules,
            Cond::Match => RuleKind::Match,
            Cond::Flagged {
                cond, src: flagged, ..
            } => RuleKind::of(cond, src || *flagged),
        }
    }
}
