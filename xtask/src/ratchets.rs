//! Sizes recorded in `xtask/ratchets.txt`: non-test files longer than `FILE_LINES`, non-test
//! functions longer than `FN_LINES`, and each crate's count of `Result<_, String>` in non-test
//! code. A new offender fails, and a recorded one must match its entry exactly, so every change
//! in size is written down in the same commit. A recorded file or function may grow only with a
//! `raised from <old>: <reason>` note on its line; a `String` count may only go down.

use std::collections::BTreeMap;
use std::path::Path;

use syn::visit::{self, Visit};

use crate::stream_policy::rust_files;

const FILE: &str = "xtask/ratchets.txt";
const ROOTS: &[&str] = &["crates", "bins"];
const FILE_LINES: usize = 800;
const FN_LINES: usize = 120;

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
enum Kind {
    FileLines,
    FnLines,
    StringErrors,
}

impl Kind {
    const ALL: [Kind; 3] = [Kind::FileLines, Kind::FnLines, Kind::StringErrors];

    fn name(self) -> &'static str {
        match self {
            Kind::FileLines => "file-lines",
            Kind::FnLines => "fn-lines",
            Kind::StringErrors => "string-errors",
        }
    }

    fn parse(name: &str) -> Option<Kind> {
        Kind::ALL.into_iter().find(|kind| kind.name() == name)
    }

    /// The size from which an entry is required; at or below it an entry is stale.
    fn limit(self) -> usize {
        match self {
            Kind::FileLines => FILE_LINES,
            Kind::FnLines => FN_LINES,
            Kind::StringErrors => 0,
        }
    }
}

type Table = BTreeMap<(Kind, String), usize>;
type Recorded = BTreeMap<(Kind, String), Entry>;

const RAISED: &str = "raised from ";
const UNSTATED: &str = "?";

#[derive(Clone, Debug, PartialEq, Eq)]
struct Entry {
    value: usize,
    raised: Option<Raise>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
struct Raise {
    from: usize,
    reason: String,
}

pub(crate) fn check(root: &Path) -> Result<(), String> {
    let text = std::fs::read_to_string(root.join(FILE)).map_err(|err| format!("{FILE}: {err}"))?;
    let recorded = parse(&text)?;
    let problems = compare(&recorded, &measure(root)?);
    if problems.is_empty() {
        Ok(())
    } else {
        Err(problems.join("\n"))
    }
}

fn parse(text: &str) -> Result<Recorded, String> {
    let mut table = Recorded::new();
    for (index, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let at = |message: &str| format!("{FILE}:{}: {message}", index + 1);
        let (sizes, raised) = match line.split_once(RAISED) {
            Some((sizes, note)) => {
                let (from, reason) = note
                    .split_once(':')
                    .ok_or_else(|| at("expected `raised from <number>: <reason>`"))?;
                let from = from
                    .trim()
                    .parse()
                    .map_err(|_| at("expected `raised from <number>: <reason>`"))?;
                let reason = reason.trim().to_string();
                (sizes, Some(Raise { from, reason }))
            }
            None => (line, None),
        };
        let fields: Vec<&str> = sizes.split_whitespace().collect();
        let [kind, key, value] = fields.as_slice() else {
            return Err(at("expected `<kind> <key> <number>`"));
        };
        let (Some(kind), Ok(value)) = (Kind::parse(kind), value.parse()) else {
            return Err(at("expected `<kind> <key> <number>`"));
        };
        if raised.is_some() && kind == Kind::StringErrors {
            return Err(at("a `Result<_, String>` count may only go down"));
        }
        if table
            .insert((kind, key.to_string()), Entry { value, raised })
            .is_some()
        {
            return Err(at("duplicate entry"));
        }
    }
    Ok(table)
}

fn render(table: &Recorded) -> String {
    let mut out = String::from(
        "# Generated by `cargo test -p xtask ratchets::tests::regenerate -- --ignored`, then reviewed.\n\
         # A number may go up only with `raised from <old>: <reason>`; see `.agents/rules.md`.\n",
    );
    for ((kind, key), entry) in table {
        out.push_str(&format!("{} {key} {}", kind.name(), entry.value));
        if let Some(raise) = &entry.raised {
            out.push_str(&format!(" {RAISED}{}: {}", raise.from, raise.reason));
        }
        out.push('\n');
    }
    out
}

/// What `regenerate` writes: measured sizes, keeping each raise note while the size is still
/// above where it was raised from, and marking a new growth for its author to explain.
fn regenerated(recorded: &Recorded, measured: &Table) -> Recorded {
    measured
        .iter()
        .map(|(key, &value)| {
            let raised = match recorded.get(key) {
                Some(entry) if key.0 != Kind::StringErrors && value > entry.value => Some(Raise {
                    from: entry
                        .raised
                        .as_ref()
                        .map_or(entry.value, |raise| raise.from),
                    reason: UNSTATED.to_string(),
                }),
                Some(entry) => entry.raised.clone().filter(|raise| value > raise.from),
                None => None,
            };
            (key.clone(), Entry { value, raised })
        })
        .collect()
}

fn compare(recorded: &Recorded, measured: &Table) -> Vec<String> {
    let mut problems = Vec::new();
    for ((kind, key), &now) in measured {
        let limit = kind.limit();
        let Some(entry) = recorded.get(&(*kind, key.clone())) else {
            if now > limit {
                problems.push(match kind {
                    Kind::StringErrors => format!(
                        "{key}: {now} `Result<_, String>` in non-test code; use a typed error"
                    ),
                    _ => format!(
                        "{key}: {now} lines, over the {} limit of {limit}; split it",
                        kind.name()
                    ),
                });
            }
            continue;
        };
        let was = entry.value;
        if now > was {
            problems.push(match kind {
                Kind::StringErrors => format!(
                    "{key}: `Result<_, String>` count grew from {was} to {now}; it may only go down"
                ),
                _ => format!(
                    "{key}: {} grew from {was} to {now}; shrink it, or write `{now} {RAISED}{}: \
                     <reason>` on its line in {FILE}",
                    kind.name(),
                    entry.raised.as_ref().map_or(was, |raise| raise.from)
                ),
            });
        } else if now <= limit {
            problems.push(format!(
                "{key}: {} is {now}, within the limit; delete its entry (was {was}) in {FILE}",
                kind.name()
            ));
        } else if now < was {
            problems.push(format!(
                "{key}: {} shrank from {was} to {now}; lower its entry in {FILE}",
                kind.name()
            ));
        }
        if let Some(raise) = &entry.raised {
            if raise.reason.is_empty() || raise.reason == UNSTATED {
                problems.push(format!(
                    "{key}: raised from {} without a reason; say why on its line in {FILE}",
                    raise.from
                ));
            }
            if raise.from <= limit {
                problems.push(format!(
                    "{key}: raised from {}, which is within the limit; a new offender is split, \
                     not recorded",
                    raise.from
                ));
            }
            if was <= raise.from {
                problems.push(format!(
                    "{key}: back at {was}, not above {}; drop its raise note in {FILE}",
                    raise.from
                ));
            }
        }
    }
    for (kind, key) in recorded.keys() {
        if !measured.contains_key(&(*kind, key.clone())) {
            problems.push(format!(
                "{key}: no longer measured as {}; delete its entry in {FILE}",
                kind.name()
            ));
        }
    }
    problems
}

fn measure(root: &Path) -> Result<Table, String> {
    let mut files = Vec::new();
    for dir in ROOTS {
        rust_files(&root.join(dir), &mut files)?;
    }
    files.sort();
    let mut table = Table::new();
    for file in files {
        let name = file
            .strip_prefix(root)
            .unwrap_or(&file)
            .to_string_lossy()
            .replace('\\', "/");
        if is_test_file(&name) {
            continue;
        }
        let source =
            std::fs::read_to_string(&file).map_err(|err| format!("{}: {err}", file.display()))?;
        let parsed = syn::parse_file(&source).map_err(|err| format!("{name}: {err}"))?;
        let mut sizes = Sizes::default();
        sizes.visit_file(&parsed);
        let lines = source.lines().count().saturating_sub(sizes.test_lines);
        if lines > 0 {
            table.insert((Kind::FileLines, name.clone()), lines);
        }
        for (function, length) in sizes.functions {
            let key = (Kind::FnLines, format!("{name}::{function}"));
            let entry = table.entry(key).or_default();
            *entry = (*entry).max(length);
        }
        if sizes.string_errors > 0 {
            *table
                .entry((Kind::StringErrors, crate_of(&name)))
                .or_default() += sizes.string_errors;
        }
    }
    table.retain(|(kind, _), value| match kind {
        Kind::StringErrors => true,
        _ => *value > kind.limit(),
    });
    Ok(table)
}

pub(crate) fn is_test_file(name: &str) -> bool {
    let file = name.rsplit('/').next().unwrap_or_default();
    name.split('/')
        .any(|part| part == "tests" || part == "benches")
        || file == "tests.rs"
        || file.ends_with("_tests.rs")
}

fn crate_of(name: &str) -> String {
    name.split('/').take(2).collect::<Vec<_>>().join("/")
}

#[derive(Default)]
struct Sizes {
    test_lines: usize,
    functions: Vec<(String, usize)>,
    string_errors: usize,
    owner: Vec<String>,
}

pub(crate) fn is_test(attrs: &[syn::Attribute]) -> bool {
    attrs.iter().any(|attr| {
        let path = attr.path();
        if path.is_ident("cfg") {
            let mut test = false;
            let _ = attr.parse_nested_meta(|meta| {
                test |= mentions_test(&meta);
                Ok(())
            });
            test
        } else {
            path.segments
                .last()
                .is_some_and(|last| last.ident == "test")
        }
    })
}

/// Whether a `cfg` predicate turns on with `test`: `test` itself, or `all(...)`/`any(...)`
/// naming it. `not(test)` does not count.
fn mentions_test(meta: &syn::meta::ParseNestedMeta<'_>) -> bool {
    if meta.path.is_ident("test") {
        return true;
    }
    if meta.path.is_ident("all") || meta.path.is_ident("any") {
        let mut test = false;
        let _ = meta.parse_nested_meta(|inner| {
            test |= mentions_test(&inner);
            Ok(())
        });
        return test;
    }
    let _ = meta.parse_nested_meta(|_| Ok(()));
    false
}

fn span_lines(start: proc_macro2::Span, end: proc_macro2::Span) -> usize {
    end.end().line.saturating_sub(start.start().line) + 1
}

fn first_token(attrs: &[syn::Attribute], fallback: proc_macro2::Span) -> proc_macro2::Span {
    attrs.first().map_or(fallback, |attr| attr.pound_token.span)
}

impl Sizes {
    fn function(&mut self, name: &syn::Ident, sig: &syn::Signature, block: &syn::Block) {
        let mut path = self.owner.clone();
        path.push(name.to_string());
        self.functions.push((
            path.join("::"),
            span_lines(sig.fn_token.span, block.brace_token.span.close()),
        ));
    }
}

impl<'ast> Visit<'ast> for Sizes {
    fn visit_item_mod(&mut self, item: &'ast syn::ItemMod) {
        if is_test(&item.attrs) {
            if let Some((brace, _)) = &item.content {
                self.test_lines += span_lines(
                    first_token(&item.attrs, item.mod_token.span),
                    brace.span.close(),
                );
            }
            return;
        }
        self.owner.push(item.ident.to_string());
        visit::visit_item_mod(self, item);
        self.owner.pop();
    }

    fn visit_item_fn(&mut self, item: &'ast syn::ItemFn) {
        if is_test(&item.attrs) {
            self.test_lines += span_lines(
                first_token(&item.attrs, item.sig.fn_token.span),
                item.block.brace_token.span.close(),
            );
            return;
        }
        self.function(&item.sig.ident, &item.sig, &item.block);
        visit::visit_item_fn(self, item);
    }

    fn visit_item_impl(&mut self, item: &'ast syn::ItemImpl) {
        if is_test(&item.attrs) {
            self.test_lines += span_lines(
                first_token(&item.attrs, item.impl_token.span),
                item.brace_token.span.close(),
            );
            return;
        }
        let owner = match &*item.self_ty {
            syn::Type::Path(path) => path
                .path
                .segments
                .last()
                .map_or_else(|| "impl".to_string(), |last| last.ident.to_string()),
            _ => "impl".to_string(),
        };
        self.owner.push(owner);
        visit::visit_item_impl(self, item);
        self.owner.pop();
    }

    fn visit_impl_item_fn(&mut self, item: &'ast syn::ImplItemFn) {
        if is_test(&item.attrs) {
            return;
        }
        self.function(&item.sig.ident, &item.sig, &item.block);
        visit::visit_impl_item_fn(self, item);
    }

    fn visit_trait_item_fn(&mut self, item: &'ast syn::TraitItemFn) {
        if let Some(block) = &item.default {
            self.function(&item.sig.ident, &item.sig, block);
        }
        visit::visit_trait_item_fn(self, item);
    }

    fn visit_type_path(&mut self, path: &'ast syn::TypePath) {
        if is_string_result(path) {
            self.string_errors += 1;
        }
        visit::visit_type_path(self, path);
    }
}

fn is_string_result(path: &syn::TypePath) -> bool {
    let Some(last) = path.path.segments.last() else {
        return false;
    };
    let syn::PathArguments::AngleBracketed(args) = &last.arguments else {
        return false;
    };
    let types: Vec<&syn::Type> = args
        .args
        .iter()
        .filter_map(|arg| match arg {
            syn::GenericArgument::Type(ty) => Some(ty),
            _ => None,
        })
        .collect();
    last.ident == "Result"
        && matches!(types.as_slice(), [_, syn::Type::Path(error)]
            if error.qself.is_none() && error.path.is_ident("String"))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
    }

    fn sizes(source: &str) -> Sizes {
        let mut sizes = Sizes::default();
        sizes.visit_file(&syn::parse_file(source).unwrap());
        sizes
    }

    #[test]
    fn the_tree_matches_the_ratchets() {
        if let Err(problems) = check(&root()) {
            panic!("{problems}");
        }
    }

    #[test]
    #[ignore = "rewrites xtask/ratchets.txt from the tree; review the diff before committing"]
    fn regenerate() {
        let recorded = std::fs::read_to_string(root().join(FILE))
            .ok()
            .and_then(|text| parse(&text).ok())
            .unwrap_or_default();
        let table = regenerated(&recorded, &measure(&root()).unwrap());
        std::fs::write(root().join(FILE), render(&table)).unwrap();
    }

    #[test]
    fn functions_are_measured_from_fn_to_closing_brace_with_their_owner() {
        let found = sizes(
            "/// doc\nfn a() {\n    1;\n}\nimpl S {\n    fn b(&self) {}\n}\nmod m {\n    fn c() {\n    }\n}\n",
        );
        assert_eq!(
            found.functions,
            [
                ("a".to_string(), 3),
                ("S::b".to_string(), 1),
                ("m::c".to_string(), 2)
            ]
        );
    }

    #[test]
    fn test_modules_and_test_functions_are_left_out() {
        let found = sizes(
            "fn a() -> Result<(), String> { Ok(()) }\n\
             #[cfg(test)]\nmod tests {\n    fn b() -> Result<(), String> { Ok(()) }\n}\n\
             #[cfg(all(test, unix))]\nfn c() {}\n#[tokio::test]\nasync fn d() {}\n\
             #[cfg(not(test))]\nfn e() {}\n",
        );
        let names: Vec<&str> = found
            .functions
            .iter()
            .map(|(name, _)| name.as_str())
            .collect();
        assert_eq!(names, ["a", "e"]);
        assert_eq!(found.string_errors, 1);
        assert_eq!(found.test_lines, 4 + 2 + 2);
    }

    #[test]
    fn only_a_string_error_counts() {
        let found = sizes(
            "fn a() -> Result<u8, String> { Ok(1) }\nfn b() -> io::Result<u8> { Ok(1) }\n\
             fn c() -> Result<u8, Error> { Ok(1) }\nfn d() -> std::result::Result<(), String> { Ok(()) }\n",
        );
        assert_eq!(found.string_errors, 2);
    }

    fn key(kind: Kind, name: &str) -> (Kind, String) {
        (kind, name.to_string())
    }

    fn plain(value: usize) -> Entry {
        Entry {
            value,
            raised: None,
        }
    }

    fn raised(value: usize, from: usize, reason: &str) -> Entry {
        Entry {
            value,
            raised: Some(Raise {
                from,
                reason: reason.to_string(),
            }),
        }
    }

    fn reports(found: &[String], expected: &[(&str, &str)]) {
        assert_eq!(found.len(), expected.len(), "{found:#?}");
        for (needle, what) in expected {
            assert!(
                found.iter().any(|p| p.starts_with(needle)),
                "{what}: {found:#?}"
            );
        }
    }

    #[test]
    fn growth_new_offenders_shrinks_and_stale_entries_are_reported() {
        let recorded = Recorded::from([
            (key(Kind::FnLines, "a.rs::grows"), plain(130)),
            (key(Kind::FnLines, "a.rs::shrinks"), plain(150)),
            (key(Kind::FnLines, "a.rs::fixed"), plain(150)),
            (key(Kind::FnLines, "a.rs::gone"), plain(150)),
            (key(Kind::StringErrors, "crates/a"), plain(3)),
            (key(Kind::StringErrors, "crates/c"), plain(1)),
        ]);
        let measured = Table::from([
            (key(Kind::FnLines, "a.rs::grows"), 131),
            (key(Kind::FnLines, "a.rs::shrinks"), 140),
            (key(Kind::FnLines, "a.rs::fixed"), 100),
            (key(Kind::FnLines, "a.rs::new"), 121),
            (key(Kind::StringErrors, "crates/a"), 3),
            (key(Kind::StringErrors, "crates/b"), 1),
            (key(Kind::StringErrors, "crates/c"), 2),
        ]);
        reports(
            &compare(&recorded, &measured),
            &[
                (
                    "a.rs::grows: fn-lines grew from 130 to 131; shrink it, or write `131 raised from 130: <reason>`",
                    "growth",
                ),
                ("a.rs::shrinks: fn-lines shrank from 150 to 140", "shrink"),
                ("a.rs::fixed: fn-lines is 100, within the limit", "fixed"),
                (
                    "a.rs::new: 121 lines, over the fn-lines limit",
                    "new offender",
                ),
                ("crates/b: 1 `Result<_, String>`", "new string error"),
                (
                    "crates/c: `Result<_, String>` count grew from 1 to 2",
                    "string growth",
                ),
                ("a.rs::gone: no longer measured", "stale"),
            ],
        );
    }

    #[test]
    fn a_raise_needs_a_reason_and_an_existing_offender() {
        let recorded = Recorded::from([
            (
                key(Kind::FileLines, "ok.rs"),
                raised(869, 809, "GSO coalesced write, split in B1"),
            ),
            (
                key(Kind::FileLines, "unstated.rs"),
                raised(869, 809, UNSTATED),
            ),
            (key(Kind::FileLines, "new.rs"), raised(869, 700, "new")),
            (
                key(Kind::FileLines, "back.rs"),
                raised(805, 809, "was larger"),
            ),
        ]);
        let measured = Table::from([
            (key(Kind::FileLines, "ok.rs"), 869),
            (key(Kind::FileLines, "unstated.rs"), 869),
            (key(Kind::FileLines, "new.rs"), 869),
            (key(Kind::FileLines, "back.rs"), 805),
        ]);
        reports(
            &compare(&recorded, &measured),
            &[
                ("unstated.rs: raised from 809 without a reason", "no reason"),
                (
                    "new.rs: raised from 700, which is within the limit",
                    "new offender",
                ),
                ("back.rs: back at 805, not above 809", "stale raise"),
            ],
        );
    }

    #[test]
    fn regenerating_marks_growth_and_keeps_live_raises() {
        let recorded = Recorded::from([
            (key(Kind::FileLines, "grows.rs"), plain(900)),
            (
                key(Kind::FileLines, "regrows.rs"),
                raised(950, 900, "earlier"),
            ),
            (key(Kind::FileLines, "kept.rs"), raised(950, 900, "earlier")),
            (key(Kind::FileLines, "back.rs"), raised(950, 900, "earlier")),
            (key(Kind::StringErrors, "crates/a"), plain(2)),
        ]);
        let measured = Table::from([
            (key(Kind::FileLines, "grows.rs"), 910),
            (key(Kind::FileLines, "regrows.rs"), 960),
            (key(Kind::FileLines, "kept.rs"), 940),
            (key(Kind::FileLines, "back.rs"), 890),
            (key(Kind::StringErrors, "crates/a"), 3),
        ]);
        assert_eq!(
            regenerated(&recorded, &measured),
            Recorded::from([
                (key(Kind::FileLines, "grows.rs"), raised(910, 900, UNSTATED)),
                (
                    key(Kind::FileLines, "regrows.rs"),
                    raised(960, 900, UNSTATED)
                ),
                (key(Kind::FileLines, "kept.rs"), raised(940, 900, "earlier")),
                (key(Kind::FileLines, "back.rs"), plain(890)),
                (key(Kind::StringErrors, "crates/a"), plain(3)),
            ])
        );
    }

    #[test]
    fn the_file_round_trips() {
        let table = Recorded::from([
            (key(Kind::FileLines, "a.rs"), plain(900)),
            (
                key(Kind::FileLines, "b.rs"),
                raised(950, 900, "GSO write: +50, split in B1"),
            ),
            (key(Kind::StringErrors, "crates/a"), plain(2)),
        ]);
        assert_eq!(parse(&render(&table)).unwrap(), table);
        assert!(parse("fn-lines a.rs\n").is_err());
        assert!(parse("file-lines a.rs 900 raised from x: why\n").is_err());
        assert!(parse("string-errors crates/a 3 raised from 2: why\n").is_err());
    }
}
